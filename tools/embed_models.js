// Packs the CC0 models in assets/models/*.glb into content/models.js as base64, because browsers
// will not fetch() local files when index.html is opened from disk. Run after changing the models:
//   node tools/embed_models.js
const fs = require('node:fs');
const path = require('node:path');

const JSON_CHUNK = 0x4e4f534a;
const BIN_CHUNK = 0x004e4942;

function pad4(buf, fill) {
  return buf.length % 4 ? Buffer.concat([buf, Buffer.alloc(4 - (buf.length % 4), fill)]) : buf;
}
function readGlb(buf) {
  const jl = buf.readUInt32LE(12);
  if (buf.readUInt32LE(16) !== JSON_CHUNK) throw new Error('no JSON chunk');
  const json = JSON.parse(buf.slice(20, 20 + jl).toString().trim());
  let bin = Buffer.alloc(0);
  if (buf.length >= 28 + jl && buf.readUInt32LE(24 + jl) === BIN_CHUNK) bin = buf.slice(28 + jl, 28 + jl + buf.readUInt32LE(20 + jl));
  return { json, bin };
}
function writeGlb(json, bin) {
  const j = pad4(Buffer.from(JSON.stringify(json)), 0x20);
  const b = pad4(bin, 0);
  const head = Buffer.alloc(12);
  head.write('glTF', 0, 'ascii');
  head.writeUInt32LE(2, 4);
  const jh = Buffer.alloc(8);
  jh.writeUInt32LE(j.length, 0);
  jh.writeUInt32LE(JSON_CHUNK, 4);
  const parts = [head, jh, j];
  if (b.length) {
    const bh = Buffer.alloc(8);
    bh.writeUInt32LE(b.length, 0);
    bh.writeUInt32LE(BIN_CHUNK, 4);
    parts.push(bh, b);
  }
  const out = Buffer.concat(parts);
  out.writeUInt32LE(out.length, 8);
  return out;
}
// Some kits (Kenney's food kit) keep their texture next to the model, not inside it. Pack any such
// image into the model's own binary chunk, so the model stands alone.
function inlineImages(buf, file, readFile) {
  const { json, bin } = readGlb(buf);
  const external = (json.images || []).filter((img) => img.uri && !/^data:/.test(img.uri));
  if (!external.length) return buf;
  let data = bin;
  json.bufferViews = json.bufferViews || [];
  json.buffers = json.buffers && json.buffers.length ? json.buffers : [{ byteLength: 0 }];
  external.forEach((img) => {
    let bytes;
    try {
      bytes = readFile(img.uri);
    } catch (e) {
      throw new Error('missing texture ' + img.uri + ' for ' + file);
    }
    data = pad4(data, 0);
    json.bufferViews.push({ buffer: 0, byteOffset: data.length, byteLength: bytes.length });
    data = Buffer.concat([data, bytes]);
    img.bufferView = json.bufferViews.length - 1;
    img.mimeType = /\.jpe?g$/i.test(img.uri) ? 'image/jpeg' : 'image/png';
    delete img.uri;
  });
  data = pad4(data, 0);
  json.buffers[0].byteLength = data.length;
  return writeGlb(json, data);
}

// every .glb in dir, and one level of kit folders (assets/models/car/police.glb is "car-police");
// a model's outside textures are looked up next to it
function listModels(dir) {
  const out = [];
  fs.readdirSync(dir).forEach((f) => {
    const full = path.join(dir, f);
    if (f.toLowerCase().endsWith('.glb')) out.push({ name: f.slice(0, -4), file: f, dir: dir });
    else if (fs.statSync(full).isDirectory() && f !== 'Textures') {
      fs.readdirSync(full).filter((g) => g.toLowerCase().endsWith('.glb')).forEach((g) => {
        out.push({ name: f + '-' + g.slice(0, -4), file: f + '/' + g, dir: full });
      });
    }
  });
  return out.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
}

function embed(dir) {
  const entries = listModels(dir).map((m) => {
    let buf = fs.readFileSync(path.join(dir, m.file));
    if (buf.length < 12 || buf.toString('ascii', 0, 4) !== 'glTF') throw new Error('not a GLB: ' + m.file);
    buf = inlineImages(buf, m.file, (uri) => fs.readFileSync(path.join(m.dir, uri)));
    return JSON.stringify(m.name) + ': ' + JSON.stringify(buf.toString('base64'));
  });
  return (
    '// Generated by tools/embed_models.js from assets/models/*.glb (CC0 models by Kenney, kenney.nl).\n' +
    '// Do not edit by hand: change the .glb files and run node tools/embed_models.js.\n' +
    '(function (root) {\n' +
    '  var data = {\n    ' + entries.join(',\n    ') + '\n  };\n' +
    "  if (typeof module === 'object' && module.exports) module.exports = data;\n" +
    '  else {\n    root.OC = root.OC || {};\n    root.OC.modelData = data;\n  }\n' +
    "})(typeof self !== 'undefined' ? self : this);\n"
  );
}

// read a generated file back into { name: Buffer } (for tests)
function parseEmbedded(src) {
  const mod = { exports: {} };
  new Function('module', 'self', src)(mod, undefined);
  const out = {};
  for (const k of Object.keys(mod.exports)) out[k] = Buffer.from(mod.exports[k], 'base64');
  return out;
}

if (require.main === module) {
  const root = path.join(__dirname, '..');
  const src = embed(path.join(root, 'assets', 'models'));
  fs.writeFileSync(path.join(root, 'content', 'models.js'), src);
  console.log('wrote content/models.js (' + (src.length / 1024 / 1024).toFixed(2) + ' MB)');
}

module.exports = { embed, parseEmbedded };
